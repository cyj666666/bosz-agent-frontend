function escapeHtml(value: string | null | undefined): string {
  return String(value ?? '')
    .replaceAll('&', '&amp;')
    .replaceAll('<', '&lt;')
    .replaceAll('>', '&gt;')
    .replaceAll('"', '&quot;')
    .replaceAll("'", '&#39;');
}

function namedTableHTML(tableName: string, rows: Array<Record<string, unknown>>, note = '', hideHeader = false): string {
  const list = Array.isArray(rows) ? rows : [];
  if (!list.length) return `<div class="table-title">${escapeHtml(tableName)}</div><p class="empty-state">暂无表格数据。</p>`;
  const headers: string[] = [];
  const seen = new Set<string>();
  list.forEach(row => {
    Object.keys(row).forEach(key => {
      if (!seen.has(key)) {
        seen.add(key);
        headers.push(key);
      }
    });
  });
  return (
    `<div class="table-title">${escapeHtml(tableName)}</div>` +
    (note ? `<div class="table-subtitle">${escapeHtml(note)}</div>` : '') +
    `<div class="table-wrap"><table>` +
    (hideHeader ? '' : `<thead><tr>${headers.map(h => `<th>${escapeHtml(h)}</th>`).join('')}</tr></thead>`) +
    `<tbody>${list
      .map(
        row =>
          `<tr>${headers
            .map(h => `<td>${escapeHtml(row[h] == null || row[h] === '' ? '——' : String(row[h]))}</td>`)
            .join('')}</tr>`,
      )
      .join('')}</tbody></table></div>`
  );
}


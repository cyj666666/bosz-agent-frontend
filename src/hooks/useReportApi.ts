export function useReportApi(reportId: string | undefined) {
  const [loading, setLoading] = useState(true);
  const [reportMeta] = useState<ReportMeta>(REPORT_META);
  const [sections] = useState<SectionItem[]>(SECTIONS);
  const [aiRiskList, setAIRiskList] = useState<AIRiskItem[]>(
    AI_RISK_LIST.map(item => ({ ...item, status: 'pending' as AIRiskStatus })),
  );
  const [sourceTemplates] = useState<SourceTemplateMap>(SOURCE_TEMPLATES);
  const [managementPanelHtml] = useState<string>(MANAGEMENT_PANEL_HTML);
  const [aiFullAnalysisHtml] = useState<string>(AI_FULL_ANALYSIS_HTML);

  useEffect(() => {
    const handleTimer = setTimeout(() => setLoading(false), 200);
    return () => clearTimeout(handleTimer);
  }, [reportId]);

  return {
    loading,
    reportMeta,
    sections,
    aiRiskList,
    sourceTemplates,
    managementPanelHtml,
    aiFullAnalysisHtml,
    setAIRiskList,
  };
}